'use strict';

const assert = require('node:assert');
const { describe } = require('../harness');
const h = require('../helpers');
const { parseLockfile } = require('../../lib/parsers');
const { ParseError } = require('../../lib/errors');
const { defaultConfig } = require('../../lib/config');
const { validateEntries } = require('../../lib/validator');

/**
 * Validate parsed fixture entries with the default policy.
 * @param {string} fixtureName Fixture file name.
 * @param {string} lockfileName Lockfile name used by the parser.
 * @returns {import('../../lib/validator').Violation[]} Violations.
 */
function validateFixture(fixtureName, lockfileName) {
  const parsed = parseLockfile(h.fixture(fixtureName), lockfileName);
  return validateEntries(parsed.entries, defaultConfig(), lockfileName);
}

describe('yarn parser', (it) => {
  it('parses the classic (v1) fixture with descriptors and resolutions', () => {
    const text = h.fixture('yarn-classic.lock');
    const parsed = parseLockfile(text, 'yarn.lock');
    assert.equal(parsed.format, 'yarn-classic');
    assert.deepEqual(
      parsed.entries.map((entry) => entry.name),
      ['express', '@corp/ui', 'poisoned', 'localpkg', 'ms'],
    );
    const express = parsed.entries.find((entry) => entry.name === 'express');
    assert.equal(express.version, '4.18.2');
    assert.equal(express.ref, 'https://registry.yarnpkg.com/express/-/express-4.18.2.tgz#a1b2c3d4');
    assert.equal(express.line, h.lineOf(text, 'express-4.18.2.tgz'));
    assert.equal(express.parser, 'yarn');
  });

  it('parses the Berry fixture and classifies npm:/workspace:/patch: specs', () => {
    const parsed = parseLockfile(h.fixture('yarn-berry.lock'), 'yarn.lock');
    assert.equal(parsed.format, 'yarn-berry');
    assert.equal(parsed.entries.length, 7);
    const express = parsed.entries.find((entry) => entry.name === 'express');
    assert.equal(express.version, '4.18.2');
    assert.equal(express.ref, 'express@npm:4.18.2');
    const local = parsed.entries.find((entry) => entry.name === 'localpkg');
    assert.equal(local.ref, 'localpkg@workspace:packages/localpkg');
  });

  it('reports the expected violations for the classic fixture', () => {
    const codes = validateFixture('yarn-classic.lock', 'yarn.lock').map((item) => item.code);
    assert.deepEqual(codes, ['HOST_NOT_ALLOWED', 'INSECURE_PROTOCOL', 'HOST_NOT_ALLOWED']);
  });

  it('reports the expected violations for the Berry fixture', () => {
    const codes = validateFixture('yarn-berry.lock', 'yarn.lock').map((item) => item.code);
    assert.deepEqual(codes, ['HOST_NOT_ALLOWED', 'GIT_HOST_NOT_ALLOWED']);
  });

  it('accepts a comments-only yarn.lock as a zero dependency project', () => {
    const text = '# yarn lockfile v1\n# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT IT DIRECTLY.\n\n';
    const parsed = parseLockfile(text, 'yarn.lock');
    assert.equal(parsed.format, 'yarn-classic');
    assert.equal(parsed.entries.length, 0);
    assert.deepEqual(validateEntries(parsed.entries, defaultConfig(), 'yarn.lock'), []);
  });

  it('accepts a Berry lockfile that only contains metadata', () => {
    const text = '__metadata:\n  version: 8\n  cacheKey: 10c0\n';
    const parsed = parseLockfile(text, 'yarn.lock');
    assert.equal(parsed.format, 'yarn-berry');
    assert.equal(parsed.entries.length, 0);
  });

  it('rejects a malformed yarn.lock with PARSE_ERROR', () => {
    assert.throws(
      () => parseLockfile('this is not a lockfile\n', 'yarn.lock'),
      (err) => {
        assert.ok(err instanceof ParseError, 'ParseError expected');
        assert.equal(err.code, 'PARSE_ERROR');
        assert.match(err.message, /no package blocks|expected a descriptor/);
        return true;
      },
    );
  });

  it('rejects an indented payload without a package header', () => {
    assert.throws(
      () => parseLockfile('  version "1.0.0"\n  resolved "https://example.test/x.tgz"\n', 'yarn.lock'),
      (err) => err instanceof ParseError && err.code === 'PARSE_ERROR',
    );
  });
});
