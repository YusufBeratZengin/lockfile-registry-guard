'use strict';

const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const { describe } = require('../harness');
const h = require('../helpers');

/**
 * Find the `policy:` header line of a human report.
 * @param {string} stdout CLI output.
 * @returns {string} Policy line, empty when missing.
 */
function policyLine(stdout) {
  return stdout.split('\n').find((line) => line.indexOf('policy:') !== -1) || '';
}

describe('cli', (it) => {
  it('keeps a positional file as the scan target after --allowed-hosts', () => {
    const target = path.join(h.FIXTURES, 'npm-v3.json');
    const result = h.runCli(['--allowed-hosts', 'registry.npmjs.org', target]);
    assert.equal(result.code, 1);
    assert.match(result.stderr, /^$/);
    assert.ok(result.stdout.includes('npm-v3.json'), 'the requested file is scanned');
    assert.equal(result.stdout.includes('NO_LOCKFILE'), false);
    const policy = policyLine(result.stdout);
    assert.ok(policy.includes('registry.npmjs.org'), 'explicit host is applied');
    assert.equal(policy.includes('npm-v3.json'), false, 'the path is not treated as a host');
    assert.equal(policy.includes('registry.yarnpkg.com'), false, 'the list was replaced');
  });

  it('accumulates repeated --add-host values', () => {
    const target = path.join(h.FIXTURES, 'npm-v3.json');
    const result = h.runCli(['--add-host', 'a.example', '--add-host', 'b.example', target]);
    const policy = policyLine(result.stdout);
    assert.ok(policy.includes('a.example'), 'first add-host is kept');
    assert.ok(policy.includes('b.example'), 'last add-host is kept');
    assert.equal(result.stdout.includes('NO_LOCKFILE'), false);
  });

  it('accepts a comma separated --allowed-hosts value', () => {
    const target = path.join(h.FIXTURES, 'npm-v3.json');
    const result = h.runCli(['--allowed-hosts', 'a.example,b.example', target]);
    const policy = policyLine(result.stdout);
    assert.ok(policy.includes('a.example'));
    assert.ok(policy.includes('b.example'));
  });

  it('passes a comments-only yarn.lock', () => {
    const dir = h.tmpDir('comments');
    try {
      h.writeFiles(dir, { 'yarn.lock': '# yarn lockfile v1\n# autogenerated, do not edit\n' });
      const result = h.runCli([path.join(dir, 'yarn.lock')]);
      assert.equal(result.code, 0, result.stdout + result.stderr);
      assert.match(result.stdout, /0 packages/);
      assert.match(result.stdout, /CI gate passed/);
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });

  it('reports PARSE_ERROR for a malformed yarn.lock', () => {
    const dir = h.tmpDir('malformed');
    try {
      h.writeFiles(dir, { 'yarn.lock': 'this is not a lockfile\n' });
      const result = h.runCli([path.join(dir, 'yarn.lock')]);
      assert.equal(result.code, 1);
      assert.match(result.stdout, /PARSE_ERROR/);
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });
});
